def shape(routes) -> tuple:
    return tuple((r.path, tuple(sorted(r.methods or ())), r.name) for r in routes)


@pytest.mark.parametrize("sign_in", [False, True])
@pytest.mark.parametrize("public_url", [None, "https://cairn.example"])
def test_the_web_views_routes_are_as_they_were(public_url, sign_in):
    assert shape(ui_routes(public_url, sign_in=sign_in)) == ROUTES


def test_the_sign_in_routes_are_as_they_were():
    accounts = SimpleNamespace(sessions=None)  # session_routes reads only its sessions
    assert shape(session_routes(accounts)) == LOGINS + LOGOUT
    assert shape(session_routes(accounts, key_login=False)) == LOGOUT


@pytest.mark.parametrize(
    ("module", "names"), [(cairn.web.ui, UI_NAMES), (cairn.store.schema, SCHEMA_NAMES)]
)
def test_every_name_the_module_defined_is_still_importable_from_it(module, names):
    assert [name for name in names if not hasattr(module, name)] == []
